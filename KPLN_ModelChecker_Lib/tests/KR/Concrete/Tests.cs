using System;
using System.Linq;
using Autodesk.Revit.DB;
using KPLN_ModelChecker_Lib.Commands.Common.KR.Concrete;
using KPLN_ModelChecker_Lib.Commands.Common.KR.Ifc;
class Tests {
 static int count;
 static void Check(bool ok,string name){if(!ok)throw new Exception(name);count++;}
 static Parameter Text(string v){return new Parameter{Text=v};}
 static Parameter Int(int v){return new Parameter{StorageType=StorageType.Integer,Integer=v};}
 static void Main(){
  Check(Rules.ClassFromCode("202512345")==25,"Third/fourth digits 25");
  Check(Rules.ClassFromCode("203512345")==35,"Third/fourth digits 35");
  Check(Rules.ClassFromCode("204512345")==45,"Third/fourth digits 45");
  foreach(var s in new[]{null,"","20251234","2025123456","302512345"," 202512345","202512345\n","20２５12345"})
   Check(Rules.ClassFromCode(s)==null,"Invalid code "+s);
  Check(Rules.ClassValue("25")==25,"Integer class");
  Check(Rules.ClassValue("25.0")==25,"Numeric string");
  Check(Rules.ClassValue("25,0")==25,"Decimal comma");
  foreach(var s in new[]{null,"","B25","NaN","-25","0"})Check(Rules.ClassValue(s)==null,"Invalid class "+s);
  Check(Rules.FastMode(new[]{25,25},true,0),"Single class");
  Check(!Rules.FastMode(new[]{25,35},true,0),"Mixed classes");
  Check(!Rules.FastMode(new int[0],true,0),"No concrete");
  Check(!Rules.FastMode(new[]{25},false,0),"Incomplete materials");
  Check(!Rules.FastMode(new[]{25},true,1),"Closed worksets");
  Check(Rules.Compare(25,25,false)=="match","Match");
  Check(Rules.Compare(25,35,false)=="class_mismatch","Mismatch");
  Check(Rules.Compare(null,25,true)=="rebar_class_empty","Missing class");
  Check(Rules.Compare(null,25,false)=="rebar_class_invalid","Invalid class");
  Check(Rules.Compare(25,null,false)=="host_class_uncertain","Unknown host class");
  var doc=new Document();var bar=doc.Add(new FamilyInstance());var type=doc.Add(new Element());bar.TypeId=type.Id;
  string error;
  Check(!Parameters.RunningMeters(bar,out error)&&error==null,"Missing running-meter flag");
  type.Set("Рзм.ПогМетрыВкл",Int(1));
  Check(Parameters.RunningMeters(bar,out error),"Type flag");
  bar.Set("Рзм.ПогМетрыВкл",Int(0));
  Check(!Parameters.RunningMeters(bar,out error),"Explicit false beats type true");
  bar.Named["Рзм.ПогМетрыВкл"][0].HasValue=false;
  Check(Parameters.RunningMeters(bar,out error),"Unset flag uses type");
  bar.Set("Рзм.ПогМетрыВкл",Text("true"));
  Check(Parameters.RunningMeters(bar,out error),"True text");
  bar.Set("Рзм.ПогМетрыВкл",Int(2));
  Check(!Parameters.RunningMeters(bar,out error),"Only 1 participates");
  bar.Set("Рзм.ПогМетрыВкл",new Parameter{StorageType=StorageType.Integer,Fail=true});
  Check(!Parameters.RunningMeters(bar,out error)&&error!=null,"Read failure is reported");
  var parent=doc.Add(new FamilyInstance());var ancestor=doc.Add(new FamilyInstance());
  bar.SuperComponent=parent;parent.SuperComponent=ancestor;
  ancestor.Set("Арм.КлассБетона",Int(35));
  Check(Parameters.RebarClass(bar).Source==ancestor,"Parent-chain fallback");
  type.Set("Арм.КлассБетона",Int(25));
  Check(Parameters.RebarClass(bar).Source==type,"Own type before parent");
  bar.Set("Арм.КлассБетона",Int(45));
  Check(Parameters.RebarClass(bar).Text=="45","Instance priority");
  bar.Set("Арм.КлассБетона",Text(" "));
  Check(Parameters.RebarClass(bar).Text=="25","Blank instance fallback");
  bar.Set("Арм.КлассБетона",new Parameter{Fail=true});
  Check(Parameters.RebarClass(bar).Error!=null,"Unreadable own class not hidden");
  bar.Named.Remove("Арм.КлассБетона");type.Named.Remove("Арм.КлассБетона");ancestor.Named.Remove("Арм.КлассБетона");
  ancestor.SuperComponent=bar;
  Check(!Parameters.RebarClass(bar).Set,"Cycle protection");
  type.Set("Орг.ИзделиеТипПодсчета",Int(2));
  Check(CountingTypeFilter.Exclude(bar,out error),"Shared counting exclusion by type");
  bar.Set("Орг.ИзделиеТипПодсчета",Int(1));
  Check(!CountingTypeFilter.Exclude(bar,out error),"Shared counting instance priority");
  var host=doc.Add(new Element());var concrete25=doc.Add(new Material());var concrete35=doc.Add(new Material());
  concrete25.Set("Мтрл.КодМатериала",Text("202512345"));concrete35.Set("Мтрл.КодМатериала",Text("203512345"));
  var reader=new Materials(doc);
  Check(reader.ElementMaterials(host).Classes.Count==0,"Unassigned project materials ignored");
  host.MaterialIds.Add(concrete25.Id);
  Check(reader.ElementMaterials(host).Classes.SetEquals(new[]{25}),"Assigned material");
  host.MaterialIds.Add(concrete35.Id);
  Check(reader.ElementMaterials(host).Classes.SetEquals(new[]{25,35}),"Read all concrete materials");
  var solid=new Solid();solid.Faces.Add(new Face{MaterialElementId=concrete25.Id});
  Check(reader.SolidMaterials(solid,reader.ElementMaterials(host)).Classes.SetEquals(new[]{25}),"Intersected body's material");
  host.FailMaterials=true;
  Check(reader.ElementMaterials(host).Errors.Count>0,"Failed material read");
  host.FailMaterials=false;host.MaterialIds.Clear();
  var hostType=doc.Add(new Element());host.TypeId=hostType.Id;
  hostType.Parameters.Add(new Parameter{StorageType=StorageType.ElementId,Reference=concrete25.Id});
  Check(reader.ElementMaterials(host).Classes.SetEquals(new[]{25}),"Type material assignment");
  var broken=doc.Add(new Material());broken.Set("Мтрл.КодМатериала",new Parameter{Fail=true});host.MaterialIds.Add(broken.Id);
  var mixed=reader.ElementMaterials(host);
  Check(mixed.Classes.Contains(25)&&mixed.Errors.Count>0,"Known concrete does not hide other material read failures");
  var concreteHost=doc.Add(new Element());concreteHost.MaterialIds.Add(concrete25.Id);
  var systemBar=doc.Add(new Autodesk.Revit.DB.Structure.RebarInSystem{HostId=concreteHost.Id,SystemId=parent.Id});
  var nativeBar=doc.Add(new Autodesk.Revit.DB.Structure.Rebar{HostId=concreteHost.Id});
  int fallbacks=0;
  Func<HostResult> fallback=()=>{fallbacks++;return new HostResult{Status="geometry_uncertain"};};
  var direct=DirectHost.Resolve(systemBar,reader.ElementMaterials,fallback);
  Check(direct.Status=="ready" && direct.Class==25 && direct.Id==concreteHost.Id && direct.Mode=="host" && fallbacks==0,"System rebar uses physical host, not SystemId or geometry");
  Check(DirectHost.Resolve(nativeBar,reader.ElementMaterials,fallback).Class==25 && fallbacks==0,"Ordinary rebar direct host");
  Check(Rules.Compare(35,direct.Class,false)=="class_mismatch","Direct host class detects mismatch");
  DirectHost.Resolve(bar,reader.ElementMaterials,fallback);Check(fallbacks==1,"IFC keeps geometry");
  nativeBar.HostId=ElementId.InvalidElementId;
  Check(DirectHost.Resolve(nativeBar,reader.ElementMaterials,fallback).Notes.Count>0 && fallbacks==2,"Missing host falls back with diagnostic");
  nativeBar.HostId=new ElementId(999999);
  DirectHost.Resolve(nativeBar,reader.ElementMaterials,fallback);Check(fallbacks==3,"Unloaded host falls back");
  nativeBar.FailHost=true;
  Check(DirectHost.Resolve(nativeBar,reader.ElementMaterials,fallback).Notes.Count>0 && fallbacks==4,"Host exception falls back");
  nativeBar.FailHost=false;nativeBar.HostId=concreteHost.Id;
  concreteHost.MaterialIds.Clear();
  DirectHost.Resolve(nativeBar,reader.ElementMaterials,fallback);Check(fallbacks==5,"Nonconcrete host falls back");
  concreteHost.MaterialIds.Add(concrete25.Id);concreteHost.MaterialIds.Add(concrete35.Id);
  Check(DirectHost.Resolve(nativeBar,reader.ElementMaterials,fallback).Class==null && fallbacks==6,"Mixed concrete classes never chosen arbitrarily");
  concreteHost.MaterialIds.Remove(concrete35.Id);concreteHost.FailMaterials=true;
  Check(DirectHost.Resolve(nativeBar,reader.ElementMaterials,fallback).Status=="geometry_uncertain" && fallbacks==7,"Partial material read preserves uncertainty");
  concreteHost.FailMaterials=false;
  Check(DirectHost.Resolve(nativeBar,reader.ElementMaterials,fallback).Status=="ready" && fallbacks==7,"Direct host does not require rebar solid");
  nativeBar.HostId=type.Id;
  var typeHost=doc.Add(new ElementType());nativeBar.HostId=typeHost.Id;
  DirectHost.Resolve(nativeBar,reader.ElementMaterials,fallback);Check(fallbacks==8,"Type cannot be a physical host");
  foreach(var resource in new Element[]{new PropertySetElement(),new AppearanceAssetElement(),new Material()}) {
   doc.Add(resource);resource.FailMaterials=true;
   resource.Parameters.Add(new Parameter{StorageType=StorageType.ElementId,Fail=true});
   Check(Materials.IsMaterialResource(resource),"Exclude material resource: "+resource.GetType().Name);
   var resourceInfo=reader.ElementMaterials(resource);
   Check(resourceInfo.Classes.Count==0 && resourceInfo.Errors.Count==0,"Do not access resource material/parameter APIs");
   nativeBar.HostId=resource.Id;
   bool accessed=false;int previous=fallbacks;
   DirectHost.Resolve(nativeBar,e=>{accessed=true;throw new Exception("Resource read must not occur");},fallback);
   Check(!accessed && fallbacks==previous+1,"Resource cannot become direct concrete host");
  }
  Check(!Materials.IsMaterialResource(concreteHost) && reader.ElementMaterials(concreteHost).Classes.Contains(25),"Real host materials still read");
  Check(!Materials.IsMaterialResource(bar),"Family instances remain candidates without geometry precondition");
  Console.WriteLine("PASS: "+count+" concrete-class, parameter, fast-mode and material cases (Revit doubles).");
 }
}